package it.forpiller.mcpforge.service;

import io.swagger.parser.OpenAPIParser;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.Operation;
import io.swagger.v3.oas.models.PathItem;
import io.swagger.v3.oas.models.parameters.Parameter;
import io.swagger.v3.parser.core.models.ParseOptions;
import io.swagger.v3.parser.core.models.SwaggerParseResult;
import it.forpiller.mcpforge.ingest.OperationDescriptor;
import it.forpiller.mcpforge.ingest.ParamDescriptor;
import it.forpiller.mcpforge.ingest.ParamLocation;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.web.client.RestClient;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;

public class OpenApiIngestService {

    private static final Logger log = LoggerFactory.getLogger(OpenApiIngestService.class);

    private final RestClient restClient;

    public OpenApiIngestService(RestClient restClient) {
        this.restClient = restClient;
    }

    public List<OperationDescriptor> ingest(String specLocation) {
        return ingest(specLocation, null, null);
    }

    public List<OperationDescriptor> ingest(
            String specLocation,
            String authHeaderName,
            String authHeaderValue) {
        String specContent = fetchSpecContent(specLocation, authHeaderName, authHeaderValue);
        try {
            return parseContent(specContent);
        } catch (IllegalArgumentException e) {
            throw new IllegalArgumentException(
                    "Impossibile leggere lo spec OpenAPI da " + specLocation + ": " + e.getMessage(), e);
        }
    }

    public String fetchSpecContent(
            String specLocation,
            String authHeaderName,
            String authHeaderValue) {
        RestClient.RequestHeadersSpec<?> request = restClient.get().uri(specLocation);
        if (authHeaderName != null && !authHeaderName.isBlank()
                && authHeaderValue != null && !authHeaderValue.isBlank()) {
            request = request.header(authHeaderName, authHeaderValue);
        }
        return request.retrieve().body(String.class);
    }

    private OperationDescriptor toDescriptor(String httpMethod, String path, Operation operation,
                                               List<Parameter> pathItemParams) {
        String operationId = operation.getOperationId();
        String rawName = (operationId != null && !isAutoGenerated(operationId))
                ? operationId
                : generateNameFromPath(httpMethod, path);
        String toolName = sanitizeToolName(rawName);

        List<ParamDescriptor> params = new ArrayList<>();

        // Path-level params first; operation-level params override by name
        Set<String> operationParamNames = operation.getParameters() != null
                ? operation.getParameters().stream().map(Parameter::getName).collect(Collectors.toSet())
                : Set.of();
        for (Parameter parameter : pathItemParams) {
            if (!operationParamNames.contains(parameter.getName())) {
                params.add(toParamDescriptor(parameter));
            }
        }

        if (operation.getParameters() != null) {
            for (Parameter parameter : operation.getParameters()) {
                params.add(toParamDescriptor(parameter));
            }
        }

        // Add path variables that appear in the URL template but are not declared in any parameter list
        Set<String> declaredNames = params.stream().map(ParamDescriptor::name).collect(Collectors.toSet());
        Matcher matcher = Pattern.compile("\\{([^}]+)}").matcher(path);
        while (matcher.find()) {
            String varName = matcher.group(1);
            if (!declaredNames.contains(varName)) {
                params.add(new ParamDescriptor(varName, ParamLocation.PATH, true, "string", null));
                declaredNames.add(varName);
            }
        }

        boolean hasRequestBody = operation.getRequestBody() != null;
        String requestBodyDescription = hasRequestBody ? operation.getRequestBody().getDescription() : null;

        String summary = operation.getSummary() != null
                ? operation.getSummary()
                : operation.getDescription();

        return new OperationDescriptor(toolName, httpMethod, path, summary, params, hasRequestBody, requestBodyDescription);
    }

    private ParamDescriptor toParamDescriptor(Parameter parameter) {
        String type = "string";
        if (parameter.getSchema() != null && parameter.getSchema().getType() != null) {
            type = parameter.getSchema().getType();
        }

        ParamLocation location = switch (parameter.getIn()) {
            case "path" -> ParamLocation.PATH;
            case "header" -> ParamLocation.HEADER;
            default -> ParamLocation.QUERY;
        };

        boolean required = Boolean.TRUE.equals(parameter.getRequired());
        return new ParamDescriptor(parameter.getName(), location, required, type, parameter.getDescription());
    }

    public List<OperationDescriptor> parseContent(String specContent) {
        ParseOptions options = new ParseOptions();
        options.setResolve(true);
        options.setResolveFully(true);

        SwaggerParseResult result = new OpenAPIParser().readContents(specContent, null, options);
        OpenAPI openApi = result.getOpenAPI();
        if (openApi == null) {
            throw new IllegalArgumentException("Spec OpenAPI non valida: " + result.getMessages());
        }

        List<OperationDescriptor> descriptors = new ArrayList<>();
        if (openApi.getPaths() == null) return descriptors;

        openApi.getPaths().forEach((path, pathItem) -> {
            List<Parameter> pathLevelParams = pathItem.getParameters() != null
                    ? pathItem.getParameters() : List.of();
            for (Map.Entry<PathItem.HttpMethod, Operation> entry : pathItem.readOperationsMap().entrySet()) {
                descriptors.add(toDescriptor(entry.getKey().name(), path, entry.getValue(), pathLevelParams));
            }
        });

        Map<String, Integer> seen = new java.util.HashMap<>();
        List<OperationDescriptor> deduped = new ArrayList<>();
        for (OperationDescriptor d : descriptors) {
            String base = d.toolName();
            int count = seen.merge(base, 1, Integer::sum);
            String finalName = (count == 1) ? base : base + "_" + count;
            deduped.add(d.withToolName(finalName));
        }
        return deduped;
    }

    private static final java.util.Set<String> GENERIC_OP_IDS = java.util.Set.of(
            "findAll", "findById", "create", "update", "delete", "save",
            "getAll", "getOne", "getById", "list", "post", "get", "put", "patch"
    );

    private boolean isAutoGenerated(String operationId) {
        return operationId.matches(".*_[0-9]+$") || GENERIC_OP_IDS.contains(operationId);
    }

    private String generateNameFromPath(String httpMethod, String path) {
        StringBuilder name = new StringBuilder(httpMethod.toLowerCase());
        for (String segment : path.split("/")) {
            if (segment.isEmpty() || segment.startsWith("{")) continue;
            if (segment.matches("api|v[0-9]+")) continue;
            name.append("_").append(segment.replace("-", "_"));
        }
        return name.toString();
    }

    private String sanitizeToolName(String raw) {
        String sanitized = raw.replaceAll("[^a-zA-Z0-9_-]", "_");
        if (sanitized.length() > 64) {
            log.warn("Nome tool ingest troncato a 64 char: '{}'", raw);
            return sanitized.substring(0, 64);
        }
        return sanitized;
    }
}
